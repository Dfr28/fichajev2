export default function BlogPostPage({ 
  params 
}: { 
  params: { slug: string } 
}) {
  const post = blogPosts.find(p => p.slug === params.slug);

  if (!post) {
    notFound();
  }

  return (
    <main className="mx-auto max-w-3xl px-4 py-16">
      {/* Header */}
      <article className="animate-fade-in">
        <div className="mb-8">
          <Link href="/blog" className="font-mono font-bold text-sm underline mb-4 inline-block">
            ← Volver al blog
          </Link>
        </div>

        <header className="mb-12 border-b-4 border-black pb-8">
          <span className="inline-block bg-black text-white px-3 py-1 font-mono text-xs font-bold mb-4">
            {post.category}
          </span>
          
          <h1 className="font-title text-5xl uppercase mb-4">{post.title}</h1>
          
          <div className="flex justify-between items-center font-mono text-sm text-gray-600">
            <time>{post.date}</time>
            <span>~15 min de lectura</span>
          </div>
        </header>

        {/* Content */}
        <div className="prose-custom font-mono text-base leading-relaxed mb-16">
          {post.content.split('\n\n').map((paragraph, idx) => {
            if (paragraph.startsWith('#')) {
              const level = paragraph.match(/^#+/)?.[0].length || 1;
              const text = paragraph.replace(/^#+\s/, '');
              const sizes = {
                1: 'text-4xl',
                2: 'text-3xl',
                3: 'text-2xl',
              };
              return (
                <h2 
                  key={idx} 
                  className={`font-title uppercase font-bold my-8 ${sizes[level as keyof typeof sizes] || 'text-xl'}`}
                >
                  {text}
                </h2>
              );
            }
            
            if (paragraph.startsWith('|')) {
              return (
                <div key={idx} className="overflow-x-auto border-4 border-black p-4 my-8 bg-gray-50">
                  <table className="w-full text-sm">
                    <tbody>
                      {paragraph.split('\n').map((row, ridx) => {
                        if (row.trim().startsWith('|') && !row.includes('---')) {
                          const cells = row.split('|').filter(c => c.trim());
                          return (
                            <tr key={ridx} className={ridx === 0 ? 'border-b-4 border-black' : 'border-b-2 border-gray-300'}>
                              {cells.map((cell, cidx) => (
                                <td key={cidx} className="px-4 py-2">
                                  {cell.trim()}
                                </td>
                              ))}
                            </tr>
                          );
                        }
                      })}
                    </tbody>
                  </table>
                </div>
              );
            }
            
            if (paragraph.startsWith('-') || paragraph.startsWith('✓')) {
              return (
                <ul key={idx} className="list-none space-y-2 my-6 ml-4">
                  {paragraph.split('\n').filter(l => l.trim()).map((line, lidx) => (
                    <li key={lidx} className="flex items-start">
                      <span className="mr-3 font-bold">•</span>
                      <span>{line.replace(/^[-✓]\s/, '')}</span>
                    </li>
                  ))}
                </ul>
              );
            }
            
            return (
              <p key={idx} className="my-6 leading-relaxed">
                {paragraph}
              </p>
            );
          })}
        </div>

        {/* Featured Image / CTA */}
        <div className="border-4 border-black p-12 text-center bg-black text-white mb-16">
          <h2 className="font-title text-3xl uppercase mb-4">¿Necesitas Control Horario?</h2>
          <p className="font-mono mb-6">
            Implementa Fichaje SaaS hoy mismo. 30 días gratis, sin tarjeta de crédito necesaria.
          </p>
          <BrutalButton href="/auth/register">Comenzar Prueba Gratuita</BrutalButton>
        </div>

        {/* Related Posts */}
        <section>
          <h3 className="font-title text-3xl uppercase mb-8">Artículos Relacionados</h3>
          <div className="grid gap-6 md:grid-cols-2">
            {blogPosts.filter(p => p.id !== post.id).slice(0, 2).map(relatedPost => (
              <Link
                key={relatedPost.id}
                href={`/blog/${relatedPost.slug}`}
                className="border-4 border-black p-6 hover:bg-gray-50 transition-colors"
              >
                <span className="inline-block bg-black text-white px-2 py-1 font-mono text-xs font-bold mb-2">
                  {relatedPost.category}
                </span>
                <h4 className="font-title text-lg uppercase mb-2">{relatedPost.title}</h4>
                <p className="font-mono text-sm text-gray-600">{relatedPost.excerpt}</p>
              </Link>
            ))}
          </div>
        </section>
      </article>
    </main>
  );
}
